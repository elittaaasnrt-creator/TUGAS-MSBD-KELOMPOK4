-- Skema lab11 deterministik. Dijalankan sebagai postgres.
CREATE EXTENSION IF NOT EXISTS pgcrypto;
DROP SCHEMA IF EXISTS lab11 CASCADE;

DO $$
DECLARE r text;
BEGIN
  FOREACH r IN ARRAY ARRAY['skema_owner','app_read','app_write','app_laporan',
                           'app_analitik','app_portal','app_auditor'] LOOP
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = r) THEN
      EXECUTE format('CREATE ROLE %I', r);
    END IF;
  END LOOP;
END $$;
ALTER ROLE skema_owner  NOLOGIN;
ALTER ROLE app_read     NOLOGIN;
ALTER ROLE app_write    NOLOGIN;
ALTER ROLE app_laporan  LOGIN PASSWORD 'lab11';
ALTER ROLE app_analitik LOGIN PASSWORD 'lab11';
ALTER ROLE app_portal   LOGIN PASSWORD 'lab11';
ALTER ROLE app_auditor  LOGIN PASSWORD 'lab11';
GRANT app_read  TO app_laporan;
GRANT app_write TO app_portal;

CREATE SCHEMA lab11 AUTHORIZATION skema_owner;
GRANT USAGE ON SCHEMA lab11 TO app_read, app_write, app_laporan, app_analitik, app_portal, app_auditor;

SET ROLE skema_owner;

