  id int PRIMARY KEY,
  pelanggan_id int NOT NULL REFERENCES lab11.pelanggan(id),
  tenant_id int NOT NULL,
  jumlah numeric(14,2) NOT NULL,
  status text NOT NULL DEFAULT 'selesai',
  dibuat_pada timestamptz NOT NULL);
